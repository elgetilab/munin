def test_designs_serialise() -> bool:
    """Everything here has to survive the trip into the tool envelope."""
    designs = [
        tails.design_overlap_tails(FRAG_A, FRAG_B).as_dict(),
        tails.design_restriction_tails(
            "EcoRI", "BamHI", INSERT_CLEAN).as_dict(),
        tails.design_sequencing_primer(_dna(600, seed=8), 300).as_dict(),
    ]
    text = json.dumps(designs)
    back = json.loads(text)
    ok = len(back) == 3
    required = {"rule", "label", "severity", "passed", "value", "threshold",
                "source"}
    for entry in back:
        for check in entry["checks"]:
            ok &= required <= set(check)
            ok &= check["severity"] in (HARD, SOFT)
            ok &= bool(check["source"])      # every rule cites something
    # The mode names in the envelope are the canonical ones; `gibson` is an
    # input alias only. "GIBSON ASSEMBLY" is a registered trademark of Codex
    # DNA (plan section 3.3), so the word may appear ONLY inside a citation
    # naming NEB's published guidance, never as an identifier or a mode value.
    ok &= back[0]["mode"] == "overlap_assembly"
    ok &= rules.normalise_mode("gibson") == back[0]["mode"]
    ok &= all(e["mode"] != "gibson" for e in back)
    for entry in back:
        for check in entry["checks"]:
            for key, value in check.items():
                if "gibson" in str(value).lower():
                    ok &= key == "source"
    return _check("designs serialise to JSON with a source on every check", ok,
                  f"{len(text)} bytes")


