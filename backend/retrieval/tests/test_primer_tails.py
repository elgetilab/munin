"""
Tests for primer/tails.py - 5' tails for cloning, and the rules on them.

Layers 2 and 3 of the primer eval plan (docs/agent-track/PRIMER-DESIGN-PLAN.md).
Pure functions, no network, no services, no fixture files.

What is being tested, and why these things
------------------------------------------
The plan names the failure this module exists to prevent. In the Bioinfoysis
re-grade (arXiv 2609.03871) the dominant residual error was assembly primer
pairs with NO VALID OVERLAP: junctions that look plausible and do not join.
Assembly primers scored 1/7 there against 14/19 for plain primer design.

So the central assertions below are not about thresholds, they are about
whether the sequences actually fit together:

  - a designed junction, ASSEMBLED, reconstructs the intended joined sequence.
    Not "the overlap is 20 nt" but "concatenating the two products gives back
    fragment A followed by fragment B, character for character".
  - `validate_overlap` rejects a junction that does not match, INCLUDING a
    near miss differing by a single base, which is the shape of the published
    failure. A Tm-based or alignment-based check would wave that through.
  - 14 nt is rejected and 15 nt accepted, at the boundary, because NEB's
    15 nt minimum is a hard one.
  - an enzyme that cuts inside the insert is caught, found by the same
    `verify.find_binding_sites` the rest of the engine searches with.
  - every one of those failures makes `rules.summarise(...)["usable"]` False,
    so nothing downstream can report a design the checks did not grant.

Thresholds themselves are editorial and are NOT asserted as correct here; see
the module docstring of primer/tails.py for which figures are published and
which are defaults. What is asserted is that the sourced/defaulted distinction
is carried honestly in the enzyme table, since that is a claim about the data
rather than about chemistry.

Sequences
---------
Synthetic or short real fragments, chosen so the right answer is visible in
the construction. The sequencing template is generated by a fixed LCG so it is
reproducible and free of accidental repeats; only its coordinates matter.

Run inside the retrieval container:
    docker exec munin-retrieval python /app/tests/test_primer_tails.py
or from backend/retrieval:
    python3 -I tests/test_primer_tails.py
"""

