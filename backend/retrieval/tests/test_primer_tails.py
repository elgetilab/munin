# The 5' end of GFP, 132 nt. Real sequence, ordinary composition.
FRAG_A = (
    "ATGAGTAAAGGAGAAGAACTTTTCACTGGAGTTGTCCCAATTCTTGTTGAATTAGATGGTGATGTT"
    "AATGGGCACAAATTTTCTGTCAGTGGAGAGGGTGAAGGTGATGCAACATACGGAAAACTTACCCTT"
)

# The lacZ-alpha multiple cloning site region of pUC19, 146 nt. Carries EcoRI,
# BamHI, HindIII and friends, which makes it a useful insert to REFUSE.
FRAG_B = (
    "ACCATGATTACGCCAAGCTTGCATGCCTGCAGGTCGACTCTAGAGGATCCCCGGGTACCGAGCTCG"
    "AATTCACTGGCCGTCGTTTTACAACGTCGTGACTGGGAAAACCCTGGCGTTACCCAACTTAATCGC"
    "CTTGCAGCACATCC"
)

# A short ORF with none of EcoRI / BamHI / HindIII / XhoI / NdeI inside it.
INSERT_CLEAN = (
    "ATGGCAGACGTCTTAACTGGTCATAAACCTGTTATCTGGACACCAATCGGTTTAGCAGACCCTAAG"
    "TTCATTGTTAAACTGGGTTCTCAAGTTGCTGACCTGTTCAAGTAA"
)

# The same insert with an EcoRI site planted in the middle: the clone-killer.
INSERT_WITH_ECORI = (
    INSERT_CLEAN[:54] + "GAATTC" + INSERT_CLEAN[54:]
)

# pydna's rendering convention, quoted in the plan (section 4): lowercase 5'
# tail, uppercase annealing region.
PYDNA_EXAMPLE = "taattaaTTTGTAATTAAAACTTAGATTAGATTGC"


def _check(name: str, ok: bool, detail: str = "") -> bool:
    label = "PASS" if ok else "FAIL"
    suffix = f" --- {detail}" if detail and not ok else ""
    print(f"[{label}] {name}{suffix}")
    return ok


def _by_rule(checks, rule):
    for c in checks:
        if c.rule == rule:
            return c
    raise AssertionError(f"no check named {rule!r}")


def _dna(n: int, seed: int) -> str:
    """
    `n` bases from a fixed linear congruential generator.

    Deterministic, so a failure is reproducible, and non-repetitive, so a
    20-mer taken out of it is unique in it. Used only where the coordinates
    matter and the bases do not.
    """
    state = seed
    out = []
    for _ in range(n):
        state = (1103515245 * state + 12345) % (1 << 31)
        out.append("ACGT"[(state >> 16) & 3])
    return "".join(out)


# --- the shared result type ----------------------------------------------
def test_display_roundtrips() -> bool:
    """
    Lowercase tail, uppercase anneal, and back again without loss.

    pydna's primers.fas uses exactly this convention and the plan cites it as
    ground truth for tail-versus-anneal segmentation, so the rendering has to
    be an inverse of the parse rather than a decoration.
    """
    parsed = TailedPrimer.from_display(PYDNA_EXAMPLE)
    ok = parsed.tail == "TAATTAA"
    ok &= parsed.anneal == "TTTGTAATTAAAACTTAGATTAGATTGC"
    ok &= parsed.display() == PYDNA_EXAMPLE
    ok &= parsed.sequence == PYDNA_EXAMPLE.upper()
    ok &= parsed.tail_length == 7 and parsed.anneal_length == 28

    # Built from parts, rendered, parsed back: the other direction.
    built = TailedPrimer(anneal="ATGCATGCATGCATGCATGC", tail="GGATCCAA")
    again = TailedPrimer.from_display(built.display())
    ok &= (again.tail, again.anneal) == (built.tail, built.anneal)

    # An untailed primer is all uppercase, which is pydna's reading too.
    bare = TailedPrimer(anneal="ATGCATGCATGCATGCATGC")
    ok &= bare.display() == "ATGCATGCATGCATGCATGC"
    ok &= TailedPrimer.from_display(bare.display()).tail == ""
    return _check("lowercase-tail / uppercase-anneal rendering round-trips", ok,
                  f"{parsed.tail!r} + {parsed.anneal!r}")


def test_display_rejects_nonsense() -> bool:
    """Case is load-bearing in this format, so mixed case must not be guessed at."""
    ok = False
    try:
        TailedPrimer.from_display("ggatccATGCatgcATGC")
    except thermo.SequenceError:
        ok = True
    all_lower = False
    try:
        TailedPrimer.from_display("ggatccatgc")
    except thermo.SequenceError:
        all_lower = True
    return _check("a malformed display string is refused, not guessed",
                  ok and all_lower)


def test_tail_is_not_judged_as_annealing_sequence() -> bool:
    """
    The core contract of the split: the rule table sees the ANNEALING region.

    A 38 nt tailed primer whose annealing region is 18 nt must be reported as
    18 nt by `primer_length`, because that is the part that has to bind. The
    opposite mistake, judging the whole oligo, is how a perfectly good assembly
    primer gets rejected for being too long and too AT-rich.
    """
    design = tails.design_overlap_tails(FRAG_A, FRAG_B)
    primer = design.forward_primer
    length_check = _by_rule(primer.checks, "primer_length")
    ok = primer.length > primer.anneal_length
    ok &= length_check.value == float(primer.anneal_length)
    ok &= _by_rule(primer.checks, "oligo_length").value == float(primer.length)
    return _check("the rule table judges the annealing region, not the tail", ok,
                  f"{primer.length} nt oligo, primer_length={length_check.value}")


# --- overlap assembly: does it actually join? ----------------------------
def test_designed_junction_assembles() -> bool:
    """
    THE test. Assemble the two products and compare to the intended sequence.

    Not "an overlap of 20 nt was returned" but "these two molecules, joined on
    their shared ends, are fragment A followed by fragment B". This is the
    assertion the Bioinfoysis failure mode would not survive.
    """
    design = tails.design_overlap_tails(FRAG_A, FRAG_B)
    up_amplicon, down_amplicon = design.amplicons(FRAG_A, FRAG_B)
    n = design.overlap_length

    # The products are what the primers say they are.
    ok = down_amplicon == design.forward_primer.tail + FRAG_B
    ok &= down_amplicon.startswith(FRAG_A[-n:])      # the tail IS A's 3' end
    ok &= up_amplicon == FRAG_A                      # default places one tail

    assembled = tails.assemble([up_amplicon, down_amplicon])
    ok &= assembled == FRAG_A + FRAG_B
    # And the overlap appears exactly once in the product, which is what
    # "joined" means as opposed to "concatenated".
    ok &= assembled.count(design.overlap) == 1
    ok &= rules.summarise(design.checks)["usable"] is True
    return _check("a designed junction assembles into the intended sequence", ok,
                  f"overlap {n} nt, {len(assembled)} nt product vs "
                  f"{len(FRAG_A) + len(FRAG_B)} nt expected")


def test_every_placement_assembles() -> bool:
    """
    Tail on the downstream primer, the upstream one, or split across both.

    The split case is the one worth having a test for: each primer carries
    half the junction, so neither half is a valid overlap on its own and only
    the assembled pair is. Getting the reverse primer's tail the right way
    round (it is a reverse complement) is the error this catches.
    """
    ok = True
    detail = []
    for placement in ("downstream", "upstream", "split"):
        design = tails.design_overlap_tails(
            FRAG_A, FRAG_B, placement=placement, overlap_length=20)
        up_amplicon, down_amplicon = design.amplicons(FRAG_A, FRAG_B)
        try:
            assembled = tails.assemble([up_amplicon, down_amplicon])
        except tails.AssemblyError as exc:
            ok = False
            detail.append(f"{placement}: {exc}")
            continue
        if assembled != FRAG_A + FRAG_B:
            ok = False
            detail.append(f"{placement}: assembled to {len(assembled)} nt")
        if design.overlap_length != 20:
            ok = False
            detail.append(f"{placement}: overlap {design.overlap_length} nt")
        if not rules.summarise(design.checks)["usable"]:
            ok = False
            detail.append(f"{placement}: checks say unusable")
    # Split really does divide the work.
    split = tails.design_overlap_tails(
        FRAG_A, FRAG_B, placement="split", overlap_length=20)
    halves = (split.forward_primer.tail_length,
              split.reverse_primer.tail_length)
    if halves != (10, 10):
        ok = False
        detail.append(f"split halves {halves}")
    return _check("downstream, upstream and split placements all assemble", ok,
                  "; ".join(detail))


def test_validate_overlap_accepts_a_real_junction() -> bool:
    upstream = _dna(120, seed=11) + "CGTATCCAGTTGACCGATCA"
    downstream = "CGTATCCAGTTGACCGATCA" + _dna(120, seed=29)
    checks = tails.validate_overlap(upstream, downstream)
    summary = rules.summarise(checks)
    ok = summary["usable"] is True
    ok &= _by_rule(checks, "overlap_identity").passed
    ok &= _by_rule(checks, "overlap_identity").value == 20.0
    ok &= _by_rule(checks, "overlap_min_length").passed
    ok &= _by_rule(checks, "overlap_preferred_length").passed
    return _check("validate_overlap accepts a junction that really matches", ok,
                  json.dumps(summary["failures"])[:120])


def test_validate_overlap_rejects_near_miss() -> bool:
    """
    One base different in the overlap, and the fragments do not join.

    This is the published failure in miniature: everything about the design
    looks right, the lengths are right, the Tm is right, and the molecules do
    not anneal. Exact identity is the only check that catches it, which is why
    `overlap_identity` is HARD and is not computed from a Tm.
    """
    shared = "CGTATCCAGTTGACCGATCA"
    upstream = _dna(120, seed=11) + shared
    # Change a single base in the middle of the downstream copy.
    broken = shared[:9] + ("A" if shared[9] != "A" else "C") + shared[10:]
    downstream = broken + _dna(120, seed=29)

    checks = tails.validate_overlap(upstream, downstream, 20)
    identity = _by_rule(checks, "overlap_identity")
    summary = rules.summarise(checks)
    ok = not identity.passed and identity.severity == HARD
    ok &= summary["usable"] is False
    ok &= "9" in identity.detail          # it names where it broke
    # The length rule must also fail rather than report a 20 nt overlap that
    # does not exist, because a downstream reader looks at numbers.
    ok &= not _by_rule(checks, "overlap_min_length").passed
    ok &= _by_rule(checks, "overlap_min_length").value == 0.0

    # Two unrelated fragments: no overlap of any length.
    none = tails.validate_overlap(_dna(80, seed=5), _dna(80, seed=6))
    ok &= not _by_rule(none, "overlap_identity").passed
    ok &= rules.summarise(none)["usable"] is False
    return _check("validate_overlap rejects a one-base near miss", ok,
                  identity.detail[:110])


def test_validate_overlap_length_boundary() -> bool:
    """15 nt passes, 14 nt does not. NEB's hard minimum, checked AT the edge."""
    left = _dna(100, seed=77)
    shared15 = "CAGTTGACCGATCAG"            # 15 nt
    shared14 = shared15[:14]                 # 14 nt

    up15 = left + shared15
    down15 = shared15 + _dna(100, seed=78)
    good = tails.validate_overlap(up15, down15, 15)
    ok = rules.summarise(good)["usable"] is True
    ok &= _by_rule(good, "overlap_min_length").passed
    # 15 works but 20 is preferred, so the SOFT rule must fire and not
    # disqualify: that distinction is the whole severity contract.
    ok &= not _by_rule(good, "overlap_preferred_length").passed
    ok &= _by_rule(good, "overlap_preferred_length").severity == SOFT

    up14 = left + shared14
    down14 = shared14 + _dna(100, seed=79)
    bad = tails.validate_overlap(up14, down14, 14)
    ok &= _by_rule(bad, "overlap_identity").passed      # it does match...
    ok &= not _by_rule(bad, "overlap_min_length").passed  # ...and is too short
    ok &= _by_rule(bad, "overlap_min_length").severity == HARD
    ok &= rules.summarise(bad)["usable"] is False
    return _check("overlap of 15 nt accepted, 14 nt rejected", ok)


def test_overlap_auto_detect_finds_the_longest_match() -> bool:
    """With no declared length, the longest exact suffix/prefix match wins."""
    shared = "ACGTTCAGGATCCATTGACCAGTA"        # 24 nt
    upstream = _dna(90, seed=3) + shared
    downstream = shared + _dna(90, seed=4)
    checks = tails.validate_overlap(upstream, downstream)
    ok = _by_rule(checks, "overlap_identity").value == 24.0
    ok &= tails.longest_exact_overlap(upstream, downstream) == 24
    ok &= tails.longest_exact_overlap(_dna(50, 1), _dna(50, 2)) == 0
    return _check("an undeclared overlap is found by longest exact match", ok)


def test_recommended_overlap_follows_neb() -> bool:
    """15-20 nt for 2-3 fragments, 20-30 for 4-6; the default prefers 20."""
    ok = tails.recommended_overlap(2) == (15, 20, 20)
    ok &= tails.recommended_overlap(3) == (15, 20, 20)
    ok &= tails.recommended_overlap(4)[:2] == (20, 30)
    ok &= tails.recommended_overlap(6)[:2] == (20, 30)
    ok &= tails.OVERLAP_MIN_NT == 15 and tails.OVERLAP_PREFERRED_NT == 20
    refused = False
    try:
        tails.recommended_overlap(1)
    except ValueError:
        refused = True
    # Past 6 fragments NEB's table stops, and the design has to say so rather
    # than extrapolate silently.
    many = tails.validate_overlap(
        _dna(60, 1) + "CAGTTGACCGATCAGTTACG",
        "CAGTTGACCGATCAGTTACG" + _dna(60, 2),
        fragment_count=8)
    ok &= not _by_rule(many, "fragment_count").passed
    ok &= rules.summarise(many)["usable"] is True   # SOFT: a warning, not a veto
    return _check("overlap ranges follow NEB's published table", ok and refused)


def test_assemble_refuses_fragments_that_do_not_join() -> bool:
    """The simulation refuses rather than concatenating hopefully."""
    raised = False
    try:
        tails.assemble([_dna(100, seed=21), _dna(100, seed=22)])
    except tails.AssemblyError:
        raised = True
    # A 14 nt shared end is below the minimum and must be refused as well.
    shared = "CAGTTGACCGATCA"
    too_short = False
    try:
        tails.assemble([_dna(60, 23) + shared, shared + _dna(60, 24)])
    except tails.AssemblyError:
        too_short = True
    # Three fragments round a circle, which is the real cloning shape.
    a, b, c = _dna(80, 31), _dna(80, 32), _dna(80, 33)
    j_ab = "TTACGCAGTTGACCGATCAG"
    j_bc = "GCATTCAGGATCCAATGCAC"
    j_ca = "ACCGTTAGCATTGACCTAGG"
    frag1 = j_ca + a + j_ab
    frag2 = j_ab + b + j_bc
    frag3 = j_bc + c + j_ca
    circle = tails.assemble([frag1, frag2, frag3], circular=True)
    closed = circle == j_ca + a + j_ab + b + j_bc + c
    return _check("assemble refuses junctions that do not join, closes circles",
                  raised and too_short and closed,
                  f"raised={raised} too_short={too_short} closed={closed}")


# --- restriction cloning --------------------------------------------------
def test_restriction_tail_structure() -> bool:
    """
    Spacer, then site, then the annealing region, and the site really is there.

    The position assertion goes through `verify.find_binding_sites` rather than
    `str.find` on purpose: that is the function the rest of the engine searches
    sequence with, so if its coordinate convention ever moved, this test would
    move with it instead of silently disagreeing.
    """
    design = tails.design_restriction_tails("EcoRI", "BamHI", INSERT_CLEAN)
    fwd = design.forward_primer
    spacer = tails.DEFAULT_SPACER_BP

    ok = fwd.tail.endswith("GAATTC")
    ok &= fwd.tail_length == spacer + 6
    ok &= fwd.anneal == INSERT_CLEAN[:fwd.anneal_length]
    ok &= fwd.display() == fwd.tail.lower() + fwd.anneal.upper()

    hits = verify.find_binding_sites(
        "GAATTC", fwd.sequence, strands=verify.PLUS)
    ok &= len(hits) == 1 and hits[0].start == spacer
    ok &= fwd.sequence[hits[0].start:hits[0].end] == "GAATTC"
    # EcoRI's site is palindromic, so it legitimately reads on both strands at
    # that one position (same convention as test_primer_verify.py).
    both = verify.find_binding_sites("GAATTC", fwd.sequence)
    ok &= len(both) == 2 and {h.start for h in both} == {spacer}

    rev = design.reverse_primer
    ok &= rev.tail.endswith("GGATCC")
    ok &= rev.anneal == thermo.reverse_complement(
        INSERT_CLEAN[-rev.anneal_length:])

    ok &= _by_rule(fwd.checks, "site_in_primer").passed
    ok &= _by_rule(fwd.checks, "spacer_length").passed
    ok &= rules.summarise(design.all_checks())["usable"] is True
    return _check("a restriction tail is spacer + site + annealing region", ok,
                  fwd.display())


def test_spacer_rules_and_provenance() -> bool:
    """
    6 bp by default, AccI at least 13, and the table says which is which.

    The provenance flag is the honest part: NEB publishes per-enzyme figures we
    could not fetch (neb.com 403s automated clients), so everything except AccI
    carries the default and admits it. A test is the right place to pin that,
    because the temptation to fill the column in from memory is real.
    """
    acci = tails.lookup_enzyme("AccI")
    ok = acci.spacer >= 13 and acci.spacer_sourced is True
    ok &= acci.site == "GTMKAC"

    defaulted = [e for e in tails.ENZYMES.values() if not e.spacer_sourced]
    ok &= all(e.spacer == tails.DEFAULT_SPACER_BP for e in defaulted)
    ok &= len(defaulted) == len(tails.ENZYMES) - 1

    # The 14 enzymes the plan asks for, with their recognition sites.
    expected = {
        "EcoRI": "GAATTC", "BamHI": "GGATCC", "HindIII": "AAGCTT",
        "XhoI": "CTCGAG", "NdeI": "CATATG", "NcoI": "CCATGG",
        "SalI": "GTCGAC", "XbaI": "TCTAGA", "NotI": "GCGGCCGC",
        "KpnI": "GGTACC", "SacI": "GAGCTC", "PstI": "CTGCAG",
        "SphI": "GCATGC", "SmaI": "CCCGGG",
    }
    for name, site in expected.items():
        ok &= tails.lookup_enzyme(name).site == site
        ok &= tails.lookup_enzyme(name.lower()).site == site

    # An AccI tail gets the longer spacer without being asked.
    acci_design = tails.design_restriction_tails("AccI", "BamHI", INSERT_CLEAN)
    ok &= acci_design.forward_primer.tail_length == acci.spacer + len(acci.site)
    ok &= _by_rule(acci_design.forward_primer.checks, "spacer_length").passed

    # Too short a spacer is a HARD failure, not a note.
    starved = tails.design_restriction_tails(
        "EcoRI", "BamHI", INSERT_CLEAN, spacer_forward=2)
    short = _by_rule(starved.forward_primer.checks, "spacer_length")
    ok &= not short.passed and short.severity == HARD
    ok &= rules.summarise(starved.all_checks())["usable"] is False
    return _check("spacer defaults to 6 bp, AccI to 13, provenance recorded", ok,
                  f"{len(defaulted)} of {len(tails.ENZYMES)} defaulted")


def test_check_internal_sites() -> bool:
    """
    An enzyme that cuts inside the insert destroys the clone, so this is HARD.

    Both directions are asserted: the catch AND the all-clear, because a check
    that never passes is as useless as one that never fires.
    """
    caught = tails.check_internal_sites("EcoRI", INSERT_WITH_ECORI)
    ok = not caught.passed and caught.severity == HARD
    ok &= caught.value == 1.0 and "54" in caught.detail

    clear = tails.check_internal_sites("EcoRI", INSERT_CLEAN)
    ok &= clear.passed and clear.value == 0.0 and clear.detail == ""

    # Several sites are all reported, not just the first.
    twice = tails.check_internal_sites(
        "BamHI", INSERT_CLEAN[:30] + "GGATCC" + INSERT_CLEAN[30:60]
        + "GGATCC" + INSERT_CLEAN[60:])
    ok &= not twice.passed and twice.value == 2.0

    # A degenerate recognition site has to be matched as a set of bases: AccI
    # (GTMKAC) cuts a SalI site (GTCGAC), which a literal string search misses.
    acci = tails.check_internal_sites("AccI", INSERT_CLEAN + "GTCGAC")
    ok &= not acci.passed and acci.value == 1.0
    ok &= tails.check_internal_sites("AccI", INSERT_CLEAN).passed

    # A site on the minus strand still counts: the enzyme cuts duplex DNA.
    ndei_rc = thermo.reverse_complement("CATATG")
    ok &= not tails.check_internal_sites(
        "NdeI", INSERT_CLEAN[:40] + ndei_rc + INSERT_CLEAN[40:]).passed

    # An insert shorter than the site cannot contain it.
    ok &= tails.check_internal_sites("NotI", "ACGTA").passed
    return _check("check_internal_sites catches a cutter and clears a clean insert",
                  ok, caught.detail[:100])


def test_internal_site_makes_the_design_unusable() -> bool:
    """The hard failure has to reach the envelope, not just the function."""
    doomed = tails.design_restriction_tails(
        "EcoRI", "BamHI", INSERT_WITH_ECORI)
    summary = rules.summarise(doomed.all_checks())
    ok = summary["usable"] is False
    ok &= any(f["rule"] == "internal_site_ecori" for f in summary["failures"])

    fine = tails.design_restriction_tails("EcoRI", "BamHI", INSERT_CLEAN)
    ok &= rules.summarise(fine.all_checks())["usable"] is True

    # The same enzyme at both ends is a SOFT warning: the clone works, it just
    # goes in either way round.
    nondirectional = tails.design_restriction_tails(
        "EcoRI", "EcoRI", INSERT_CLEAN)
    same = _by_rule(nondirectional.checks, "distinct_enzymes")
    ok &= not same.passed and same.severity == SOFT
    ok &= rules.summarise(nondirectional.all_checks())["usable"] is True
    return _check("an enzyme cutting inside the insert makes the design unusable",
                  ok, json.dumps(summary["failures"][:1])[:120])


# --- sequencing -----------------------------------------------------------
def test_sequencing_primer_offset_and_direction() -> bool:
    """
    The primer sits at the requested offset and reads toward the feature.

    Offset is measured from the primer's 3' end to the feature, because that is
    the distance the polymerase covers before reaching the region of interest.
    The low-quality opening of the read then falls in that gap rather than on
    the feature.
    """
    template = _dna(600, seed=4242)
    feature = 300

    fwd = tails.design_sequencing_primer(template, feature, offset=100)
    ok = fwd.strand == verify.PLUS
    ok &= feature - fwd.end == 100            # the requested offset, exactly
    ok &= fwd.end < feature                   # reads toward it, not away
    ok &= fwd.sequence == template[fwd.start:fwd.end]
    ok &= fwd.primer.tail == ""               # sequencing primers take no tail
    ok &= fwd.primer.display() == fwd.sequence.upper()

    rev = tails.design_sequencing_primer(
        template, feature, direction="reverse", offset=100)
    ok &= rev.strand == verify.MINUS
    ok &= rev.start - feature == 100
    ok &= rev.sequence == thermo.reverse_complement(
        template[rev.start:rev.end])
    # It really does read back toward the feature.
    ok &= rev.start > feature

    # And both are found where they claim to be, by the in-silico oracle.
    for design in (fwd, rev):
        sites = verify.find_binding_sites(design.sequence, template)
        ok &= len(sites) == 1
        ok &= sites[0].strand == design.strand
        ok &= sites[0].start == design.start
        ok &= rules.summarise(design.all_checks())["usable"] is True
    return _check("a sequencing primer sits at the offset and reads toward the "
                  "feature", ok,
                  f"fwd {fwd.start}..{fwd.end} rev {rev.start}..{rev.end}")


def test_sequencing_offset_window_is_soft() -> bool:
    """50-150 nt is a convention, so outside it is a warning, not a veto."""
    template = _dna(600, seed=99)
    close = tails.design_sequencing_primer(template, 300, offset=10)
    off = _by_rule(close.checks, "read_offset")
    ok = not off.passed and off.severity == SOFT
    ok &= rules.summarise(close.all_checks())["usable"] is True
    inside = tails.design_sequencing_primer(template, 300, offset=50)
    ok &= _by_rule(inside.checks, "read_offset").passed
    ok &= _by_rule(
        tails.design_sequencing_primer(template, 300, offset=150).checks,
        "read_offset").passed
    return _check("the 50-150 nt read offset is a soft preference", ok)


def test_sequencing_primer_refuses_impossible_placement() -> bool:
    """Off the end of a linear template is an error, not a wrapped guess."""
    template = _dna(300, seed=7)
    raised = False
    try:
        tails.design_sequencing_primer(template, 50, offset=100)
    except thermo.SequenceError:
        raised = True
    # On a circular template the same placement is legitimate and wraps.
    wrapped = tails.design_sequencing_primer(
        template, 50, offset=100, circular=True)
    ok = raised and wrapped.start > 50
    ok &= rules.summarise(wrapped.all_checks())["usable"] is True
    return _check("a primer off the end of a linear template is refused", ok,
                  f"raised={raised}")


def test_duplicate_binding_site_is_hard() -> bool:
    """Two exact sites give a mixed trace, so the primer is unusable."""
    core = _dna(200, seed=321)
    repeated = core + core          # every 20-mer now occurs twice
    design = tails.design_sequencing_primer(repeated, 200, offset=100)
    unique = _by_rule(design.checks, "unique_in_template")
    ok = not unique.passed and unique.severity == HARD
    ok &= rules.summarise(design.all_checks())["usable"] is False
    return _check("a sequencing primer with two binding sites is unusable", ok,
                  unique.detail[:90])


